#!/usr/bin/env python3
"""Build the README table "The satellites — what each one does" from the app's own data.

Sources, all in this repository:
  static/data/missions.json   facts per satellite (sourced; see its "sources" lists)
  server.py GIBS_LAYERS       which imagery layers each satellite feeds (by NORAD id), with titles
  static/js/sats.js FLEET     which 3D model the satellite gets
Nothing is added by hand except the two layers that are not GIBS imagery (NISAR footprints, SWOT heights).
Unknown fields are left out, not guessed.

  python3 scripts/gen_satellites_table.py           rewrite the table in README.md between the markers
  python3 scripts/gen_satellites_table.py --check   exit 1 if README.md is out of date (used by check.sh)
  python3 scripts/gen_satellites_table.py --print   print the table only
"""
import ast
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
START, END = "<!-- satellites:start -->", "<!-- satellites:end -->"
EXTRA = {  # app layers that are not GIBS imagery (see static/js/data.js)
    65053: ["NISAR footprints (ASF)"],
    54754: ["SWOT river & lake heights (PO.DAAC Hydrocron)"],
}


def gibs_layers():
    tree = ast.parse((ROOT / "server.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "GIBS_LAYERS" for t in node.targets):
            out = []
            for call in node.value.elts:
                out.append({kw.arg: ast.literal_eval(kw.value) for kw in call.keywords})
            return out
    raise SystemExit("GIBS_LAYERS not found in server.py")


def fleet_models():
    js = (ROOT / "static/js/sats.js").read_text(encoding="utf-8")
    return {int(n): slug for n, slug in re.findall(r"(\d{5}): \['#[0-9a-fA-F]{6}', '[^']*', '([a-z0-9]+)'\]", js)}


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def build():
    d = json.loads((ROOT / "static/data/missions.json").read_text(encoding="utf-8"))
    layers = gibs_layers()
    title = {l["id"]: l["title"] for l in layers}
    by_sat = {}
    for l in layers:
        if l.get("sat"):
            by_sat.setdefault(l["sat"], []).append(l["id"])
    models = fleet_models()
    rows, seen = [], {}
    for norad, m in d["missions"].items():
        norad = int(norad)
        name = re.sub(r" — satellite \d+$", "", m["mission"])
        ids = list(dict.fromkeys(list(m.get("gibs_layers") or []) + by_sat.get(norad, [])))
        app = [title.get(i, i) for i in ids] + EXTRA.get(norad, [])
        slug = models.get(norad)
        model = None
        if slug and slug != "generic":
            model = "3D model (NASA 3D Resources)"
        elif slug == "generic":
            model = "generic 3D model"
        if name in seen:  # twin satellites (GRACE-FO 1 and 2) share one row
            seen[name]["norad"].append(norad)
            continue
        inst = "<br>".join("**%s**: %s" % (cell(i["name"]), cell(i["desc"])) if i.get("desc") else "**%s**" % cell(i["name"])
                           for i in m.get("instruments") or [])
        launch = cell(m["launch_date"]) if m.get("launch_date") else ""
        row = {"name": name, "norad": [norad], "agency": cell(m.get("operator") or ""), "launch": launch,
               "orbit": cell(m.get("orbit") or ""), "inst": inst, "measures": cell(m.get("measures") or ""),
               "app": "<br>".join(cell(a) for a in app + ([model] if model else []))}
        seen[name] = row
        rows.append(row)
    out = ["| Satellite | Agency | Launch | Orbit | Instruments, in plain words | What it measures | In the app |",
           "|---|---|---|---|---|---|---|"]
    for r in rows:
        ids = ", ".join(str(n) for n in r["norad"])
        sat = "**%s**<br><sub>NORAD %s</sub>" % (cell(r["name"]), ids)
        if m_page := d["missions"][str(r["norad"][0])].get("mission_page"):
            sat = "**[%s](%s)**<br><sub>NORAD %s</sub>" % (cell(r["name"]), m_page, ids)
        out.append("| %s | %s | %s | %s | %s | %s | %s |" % (sat, r["agency"], r["launch"], r["orbit"], r["inst"],
                                                        r["measures"], r["app"] or "position, orbit and passes"))
    note = ("<sub>Generated by `scripts/gen_satellites_table.py` from `static/data/missions.json` (facts checked against the "
            "pages listed in its `sources`, as of %s; anything that could not be confirmed is left out), the layer list in "
            "`server.py` and the model list in `static/js/sats.js`. Every satellite also gets its live position, orbit "
            "track, passes over you and, where known, its instrument swath.</sub>" % d["generated"][:10])
    return "\n".join(out) + "\n\n" + note


def main():
    table = build()
    if "--print" in sys.argv:
        print(table)
        return
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit("README.md has no %s ... %s markers" % (START, END))
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: START + "\n" + table + "\n" + END, text, flags=re.S)
    if "--check" in sys.argv:
        if new != text:
            print("README.md satellites table is out of date: run python3 scripts/gen_satellites_table.py")
            sys.exit(1)
        print("README satellites table up to date")
        return
    if new != text:
        readme.write_text(new, encoding="utf-8")
        print("README.md table updated (%d satellites)" % table.count("<sub>NORAD"))
    else:
        print("README.md table already up to date")


if __name__ == "__main__":
    main()
